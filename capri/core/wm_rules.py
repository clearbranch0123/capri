"""
CAPRI // Niri & Hyprland Window Manager Rules Generator & Safe Installer (v3.0 — Wave 5).

Strictly supports Niri (`config.kdl` / `config.d/90-user-extra.kdl`) and
Hyprland (`hyprland.conf`) with:
- Marker-fenced idempotent blocks (`CAPRI-WM-RULES BEGIN/END`)
- Dry-run preview by default (never mutates user configs unless explicitly applied)
- Timestamped `.capri.bak` backups before any write
- Verification helper for `/doctor`
"""

from __future__ import annotations

import re
import shutil
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Literal, Optional

from .compositor import detect_compositor

WMTarget = Literal["niri", "hyprland"]

_NIRI_BEGIN = "// >>> CAPRI-WM-RULES BEGIN >>>"
_NIRI_END = "// <<< CAPRI-WM-RULES END <<<"
_HYPR_BEGIN = "# >>> CAPRI-WM-RULES BEGIN >>>"
_HYPR_END = "# <<< CAPRI-WM-RULES END <<<"


@dataclass(frozen=True)
class WMRulesResult:
    wm: WMTarget
    target_path: Path
    snippet: str
    applied: bool
    created_file: bool = False
    updated_existing_block: bool = False
    backup_path: Optional[Path] = None
    message: str = ""


def generate_niri_rules(
    include_hotkey: bool = True,
    *,
    toggle_hotkey: str = "Mod+Shift+C",
    ask_hotkey: str = "Mod+Shift+A",
) -> str:
    """Generate valid Niri KDL rules for `capri-avatar`, `capri-cyberdeck`, `Capri Quick Ask`, and optional hotkeys."""
    lines = [
        _NIRI_BEGIN,
        "// Auto-generated by Capri AI Companion (--wm-rules). Safe to re-run.",
        "window-rule {",
        '    match app-id=r#"^capri-avatar$"#',
        "    open-floating true",
        "    open-focused false",
        '    default-floating-position x=30 y=30 relative-to="bottom-right"',
        "    draw-border-with-background false",
        "    border { off; }",
        "    focus-ring { off; }",
        "    shadow { off; }",
        "}",
        "",
        "window-rule {",
        '    match app-id=r#"^capri-cyberdeck$"#',
        "    default-column-width { proportion 0.55; }",
        "    geometry-corner-radius 12",
        "    clip-to-geometry true",
        "}",
        "",
        "window-rule {",
        '    match title=r#"^Capri Quick Ask$"#',
        "    open-floating true",
        "    draw-border-with-background false",
        "    border { off; }",
        "    focus-ring { off; }",
        "    shadow { off; }",
        "}",
    ]
    if include_hotkey:
        lines.extend([
            "",
            "// Change binds below if already used by your compositor (or run `/wm-rules niri apply --no-hotkey`)",
            "binds {",
            f'    {toggle_hotkey} {{ spawn "capri-deck" "--toggle"; }}',
            f'    {ask_hotkey} {{ spawn "capri-deck" "--ask"; }}',
            "}",
        ])
    lines.append(_NIRI_END)
    return "\n".join(lines) + "\n"


def generate_hyprland_rules(
    include_hotkey: bool = True,
    *,
    toggle_hotkey: str = "SUPER SHIFT, C",
    ask_hotkey: str = "SUPER SHIFT, A",
) -> str:
    """Generate valid Hyprland `windowrulev2` rules for `capri-avatar`, `capri-cyberdeck`, `Capri Quick Ask`, and optional hotkeys."""
    lines = [
        _HYPR_BEGIN,
        "# Auto-generated by Capri AI Companion (--wm-rules). Safe to re-run.",
        "windowrulev2 = float, class:^(capri-avatar)$",
        "windowrulev2 = pin, class:^(capri-avatar)$",
        "windowrulev2 = nofocus, class:^(capri-avatar)$",
        "windowrulev2 = noborder, class:^(capri-avatar)$",
        "windowrulev2 = noshadow, class:^(capri-avatar)$",
        "windowrulev2 = noblur, class:^(capri-avatar)$",
        "windowrulev2 = size 300 420, class:^(capri-avatar)$",
        "windowrulev2 = move 100%-330 100%-450, class:^(capri-avatar)$",
        "windowrulev2 = opacity 0.98 0.96, class:^(capri-cyberdeck)$",
        "windowrulev2 = float, title:^(Capri Quick Ask)$",
        "windowrulev2 = pin, title:^(Capri Quick Ask)$",
        "windowrulev2 = noborder, title:^(Capri Quick Ask)$",
        "windowrulev2 = noshadow, title:^(Capri Quick Ask)$",
    ]
    if include_hotkey:
        lines.append("# Change binds below if already used by your compositor (or run `/wm-rules hyprland apply --no-hotkey`)")
        lines.append(f"bind = {toggle_hotkey}, exec, capri-deck --toggle")
        lines.append(f"bind = {ask_hotkey}, exec, capri-deck --ask")
    lines.append(_HYPR_END)
    return "\n".join(lines) + "\n"


def _sanitize_hotkey(raw: Optional[str], default: str) -> str:
    """Reject empty or unsafe hotkey strings containing config-breaking characters."""
    if not raw:
        return default
    cleaned = re.sub(r"[\r\n{}\"'`;#]+", "", str(raw)).strip()
    return cleaned or default


def _extract_existing_hotkeys(existing: str, wm: WMTarget) -> tuple[Optional[str], Optional[str]]:
    """Preserve user-customized toggle/ask hotkeys from an existing CAPRI-WM-RULES block on re-apply."""
    begin_m, end_m = (_HYPR_BEGIN, _HYPR_END) if wm == "hyprland" else (_NIRI_BEGIN, _NIRI_END)
    b_idx = existing.find(begin_m)
    e_idx = existing.find(end_m)
    if b_idx == -1 or e_idx == -1 or e_idx < b_idx:
        return None, None
    block = existing[b_idx : e_idx + len(end_m)]
    if wm == "hyprland":
        m_tog = re.search(r"^\s*bind\s*=\s*([^,\n]+,\s*[^,\n]+),\s*exec,\s*capri-deck\s+--toggle\b", block, re.MULTILINE)
        m_ask = re.search(r"^\s*bind\s*=\s*([^,\n]+,\s*[^,\n]+),\s*exec,\s*capri-deck\s+--ask\b", block, re.MULTILINE)
    else:
        m_tog = re.search(r'^\s*([^\s{]+)\s*\{\s*spawn\s+"capri-deck"\s+"--toggle";', block, re.MULTILINE)
        m_ask = re.search(r'^\s*([^\s{]+)\s*\{\s*spawn\s+"capri-deck"\s+"--ask";', block, re.MULTILINE)
    return (
        m_tog.group(1).strip() if m_tog else None,
        m_ask.group(1).strip() if m_ask else None,
    )


def generate_wm_rules(
    wm: WMTarget,
    include_hotkey: bool = True,
    *,
    toggle_hotkey: Optional[str] = None,
    ask_hotkey: Optional[str] = None,
) -> str:
    if wm == "hyprland":
        return generate_hyprland_rules(
            include_hotkey=include_hotkey,
            toggle_hotkey=_sanitize_hotkey(toggle_hotkey, "SUPER SHIFT, C"),
            ask_hotkey=_sanitize_hotkey(ask_hotkey, "SUPER SHIFT, A"),
        )
    return generate_niri_rules(
        include_hotkey=include_hotkey,
        toggle_hotkey=_sanitize_hotkey(toggle_hotkey, "Mod+Shift+C"),
        ask_hotkey=_sanitize_hotkey(ask_hotkey, "Mod+Shift+A"),
    )


def resolve_niri_config_target(config_dir: Optional[Path] = None) -> Path:
    """
    Resolve best Niri target file:
    - If modular `config.d/90-user-extra.kdl` exists AND `config.kdl` includes it (e.g. iNiR),
      target `90-user-extra.kdl` so base config files remain untouched.
    - Otherwise target `config.kdl`.
    """
    niri_dir = config_dir or (Path.home() / ".config" / "niri")
    main_kdl = niri_dir / "config.kdl"
    user_extra = niri_dir / "config.d" / "90-user-extra.kdl"
    if user_extra.exists() and main_kdl.exists():
        try:
            main_text = main_kdl.read_text(encoding="utf-8", errors="replace")
            if "90-user-extra.kdl" in main_text:
                return user_extra
        except OSError:
            pass
    return main_kdl


def resolve_hyprland_config_target(config_dir: Optional[Path] = None) -> Path:
    hypr_dir = config_dir or (Path.home() / ".config" / "hypr")
    return hypr_dir / "hyprland.conf"


def _upsert_fenced_block(existing: str, block: str, begin_marker: str, end_marker: str) -> tuple[str, bool]:
    """Idempotently replace an existing fenced block or append cleanly at EOF."""
    b_idx = existing.find(begin_marker)
    e_idx = existing.find(end_marker)
    if b_idx != -1 and e_idx != -1 and e_idx >= b_idx:
        after_end = e_idx + len(end_marker)
        if after_end < len(existing) and existing[after_end : after_end + 1] == "\n":
            after_end += 1
        updated = existing[:b_idx] + block + existing[after_end:]
        return updated, True

    sep = "" if (not existing or existing.endswith("\n\n")) else ("\n" if existing.endswith("\n") else "\n\n")
    return existing + sep + block, False


def check_wm_rules_installed(wm: Optional[str] = None, config_dir: Optional[Path] = None) -> tuple[bool, Optional[Path]]:
    """
    Check whether Capri window rules (`CAPRI-WM-RULES` block or manual `capri-avatar` rule)
    are present in Niri or Hyprland config files.
    """
    target_wm = wm or detect_compositor()
    if target_wm == "niri":
        base = config_dir or (Path.home() / ".config" / "niri")
        candidates: list[Path] = []
        if (base / "config.kdl").exists():
            candidates.append(base / "config.kdl")
        if (base / "config.d").is_dir():
            candidates.extend(sorted((base / "config.d").glob("*.kdl")))
        for fpath in candidates:
            try:
                txt = fpath.read_text(encoding="utf-8", errors="replace")
                if _NIRI_BEGIN in txt or "capri-avatar" in txt:
                    return True, fpath
            except OSError:
                continue
        return False, None

    if target_wm == "hyprland":
        base = config_dir or (Path.home() / ".config" / "hypr")
        candidates = []
        if (base / "hyprland.conf").exists():
            candidates.append(base / "hyprland.conf")
        if base.is_dir():
            candidates.extend(sorted(p for p in base.rglob("*.conf") if p not in candidates))
        for fpath in candidates:
            try:
                txt = fpath.read_text(encoding="utf-8", errors="replace")
                if _HYPR_BEGIN in txt or "capri-avatar" in txt:
                    return True, fpath
            except OSError:
                continue
        return False, None

    return False, None


def install_wm_rules(
    wm: Optional[str] = None,
    *,
    config_dir: Optional[Path] = None,
    target_file: Optional[Path] = None,
    dry_run: bool = True,
    include_hotkey: bool = True,
    toggle_hotkey: Optional[str] = None,
    ask_hotkey: Optional[str] = None,
) -> WMRulesResult:
    """
    Generate (and optionally install with timestamped backup) Niri or Hyprland rules for Capri.
    Preserves user-customized hotkeys from an existing CAPRI-WM-RULES block unless explicitly overridden.
    """
    resolved_wm = (wm or "").strip().lower()
    if resolved_wm not in ("niri", "hyprland"):
        detected = detect_compositor()
        resolved_wm = detected if detected in ("niri", "hyprland") else "niri"

    wm_lit: WMTarget = "hyprland" if resolved_wm == "hyprland" else "niri"
    begin_m, end_m = (_HYPR_BEGIN, _HYPR_END) if wm_lit == "hyprland" else (_NIRI_BEGIN, _NIRI_END)

    if target_file is not None:
        dest = Path(target_file)
    elif wm_lit == "hyprland":
        dest = resolve_hyprland_config_target(config_dir=config_dir)
    else:
        dest = resolve_niri_config_target(config_dir=config_dir)

    # Preserve existing custom hotkeys if user edited their WM config block and didn't pass overrides
    eff_toggle = toggle_hotkey
    eff_ask = ask_hotkey
    if include_hotkey and dest.exists() and (eff_toggle is None or eff_ask is None):
        try:
            prev_text = dest.read_text(encoding="utf-8", errors="replace")
            ex_toggle, ex_ask = _extract_existing_hotkeys(prev_text, wm_lit)
            if eff_toggle is None and ex_toggle:
                eff_toggle = ex_toggle
            if eff_ask is None and ex_ask:
                eff_ask = ex_ask
        except OSError:
            pass

    snippet = generate_wm_rules(
        wm_lit,
        include_hotkey=include_hotkey,
        toggle_hotkey=eff_toggle,
        ask_hotkey=eff_ask,
    )

    if dry_run:
        return WMRulesResult(
            wm=wm_lit,
            target_path=dest,
            snippet=snippet,
            applied=False,
            message=f"Предпросмотр правил {wm_lit.capitalize()} для `{dest}` (режим dry-run, файл не изменён).",
        )

    dest.parent.mkdir(parents=True, exist_ok=True)
    backup_path: Optional[Path] = None
    created = not dest.exists()
    existing = ""
    if dest.exists():
        existing = dest.read_text(encoding="utf-8", errors="replace")
        ts = time.strftime("%Y%m%d-%H%M%S")
        backup_path = dest.with_name(f"{dest.name}.{ts}.capri.bak")
        shutil.copy2(dest, backup_path)

    new_content, replaced = _upsert_fenced_block(existing, snippet, begin_m, end_m)
    dest.write_text(new_content, encoding="utf-8")

    action_word = "обновлён" if replaced else ("создан" if created else "дополнен")
    bak_note = f" (бэкап: `{backup_path}`)" if backup_path else ""
    return WMRulesResult(
        wm=wm_lit,
        target_path=dest,
        snippet=snippet,
        applied=True,
        created_file=created,
        updated_existing_block=replaced,
        backup_path=backup_path,
        message=f"Конфиг {wm_lit.capitalize()} `{dest}` успешно {action_word}{bak_note}.",
    )
